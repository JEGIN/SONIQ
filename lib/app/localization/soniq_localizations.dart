    'de' => 'Deutsch',
    'ja' => '日本語',
    'zh' => '简体中文',
    _ => 'English',
  };

  static Locale? localeForCode(String code) => code == 'system'
      ? null
      : Locale(
          supportedLocales.any((locale) => locale.languageCode == code)
              ? code
              : 'en',
        );

  static Locale resolve(Locale? candidate) {
    if (candidate != null) {
      for (final supported in supportedLocales) {
        if (supported.languageCode == candidate.languageCode) return supported;
      }
    }
    return const Locale('en');
  }

  static SoniqLocalizations of(BuildContext context) =>
      Localizations.of<SoniqLocalizations>(context, SoniqLocalizations) ??
      const SoniqLocalizations(Locale('en'));
}

class SoniqLocalizationsDelegate
    extends LocalizationsDelegate<SoniqLocalizations> {
  const SoniqLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => SoniqLocalizations.supportedLocales.any(
    (supported) => supported.languageCode == locale.languageCode,
  );

  @override
  Future<SoniqLocalizations> load(Locale locale) async {
    await initializeDateFormatting(locale.toString());
    Intl.defaultLocale = locale.toString();
    return SoniqLocalizations(locale);
  }

  @override
  bool shouldReload(SoniqLocalizationsDelegate old) => false;
}
